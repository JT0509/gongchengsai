//   安装位置：车体左侧（左前轮与左后轮之间），车头朝前时在左侧
//   用途：数线计数——车沿辐射线行进时，车身会横向压过大圆/小圆的圆线，
//         侧方灰度读到「黑」的上升沿即计一次，从而判断径向位置 r_level
// ============================================================================

void    S_GW_Init(void);   // PD12 上拉输入
uint8_t S_GW_Read(void);   // 返回 0/1，约定 1=黑线、0=白（极性待实车标定）

#endif
