#ifndef _trace_H
#define _trace_H

#include "main.h"

// ============================================================================
// 巡线参数（实车标定时只调这几处）
//   LINE_SPEED 巡线基础速度（速度寄存器 int8_t 范围 -127~127）
//   U_LIMIT    差速量限幅（必须 < LINE_SPEED，保证任一侧轮子都不会反向，
//              即不会原地打转；当前 5/12 ≈ 42%）
//   KP_LINE    P 增益（对滤波后误差）：u = KP_LINE*e + KD_LINE*(e-e_last)
//              要足够大，偏 1 格（e≈5）就应产生明显差速，否则车会“只会直行”
//   KD_LINE    D 增益（微分项，对滤波后误差取，抑制震荡）
//   POS_FILTER_ALPHA 位置低通系数（0~1，越小越平滑但越滞后）
//   LOST_TURN  丢线（全白）时的回找差速量：朝丢线前方向小角度画弧，替代原地快旋
//   LOST_SWEEP_TICKS 丢线且方向未知时的扫线半周期（每 10ms 一拍）
// ----------------------------------------------------------------------------
//  8 路数字灰度误差每格 10（0~70 中心 35），滤波后 e ∈ [-35,35]。
//  例：KP_LINE=0.6 → 偏 1 格 u≈3、偏 2 格 u≈6（再被 U_LIMIT 限到 5）
//  KP_LINE / KD_LINE / POS_FILTER_ALPHA 同时被 nav.c 的 Nav_PD 使用
// ============================================================================
#define LINE_SPEED 12
#define TRACE_BACK_SPEED 12  // 后退循迹速度（与前进分开调：后退打滑/过冲时只改这个）
#define U_LIMIT    5
#define LOST_TURN  4
#define LOST_SWEEP_TICKS 40

#define KP_LINE    0.6f
#define KD_LINE    0.20f

// ----------------------------------------------------------------------------
// 板载 LED 循线状态指示：板载 LED 已坏，关闭该调试输出
// ----------------------------------------------------------------------------
#define LINE_LED_DEBUG 0

// ----------------------------------------------------------------------------
// 调试开关：置 1 时 Diff_Drive 不向驱动板写速度（车完全不动），
// 但 Line_Follow 仍照常读灰度、更新 DBG_* 变量，方便打断点单步观察。
// 调完记得改回 0，否则车不会跑。
// ----------------------------------------------------------------------------
#define TRACE_MOTOR_DISABLE 0

// ----------------------------------------------------------------------------
// 纠偏方向符号（LINE_SIGN）：灰度左右映射的符号开关
//   现象：「越纠越偏」/ 车朝线的反方向跑 → 说明 pos 正负与车体左右相反，
//         把 LINE_SIGN 改成 (-1) 即可。
// ----------------------------------------------------------------------------
#define LINE_SIGN (+1)

// ----------------------------------------------------------------------------
// 位置低通滤波（POS_FILTER_ALPHA）—— trace.c 与 nav.c 共用
//   8 路灰度的质心位置是离散量（相邻测量跳 10~20），直接 PD 会剧烈震荡。
//   先对位置做一阶低通 pos_f += ALPHA*(pos - pos_f)，再算误差做 PD。
// ----------------------------------------------------------------------------
#define POS_FILTER_ALPHA 0.4f

// ----------------------------------------------------------------------------
// 丢线 / 全黑处理
//   全黑（-2）：交点/宽线/圆心，保持直行通过（不停车、不打转）
//   全白（-1）：丢线，向前时朝「丢线前线的方向」小角度画弧回找；
//              方向未知时左右慢速扫线（LOST_SWEEP_TICKS 定半周期）；向后保持直行
// ----------------------------------------------------------------------------

// ============================================================================
// 原地旋转弯参数（实车标定）
//   TURN_KP     转角比例：err 大时转得快、接近目标自动减速（丝滑的关键）
//   TURN_MAX    最高转速限幅（防起步猛冲/打滑）
//   TURN_MIN    最低转速（避免快到位时爬行不转）
//   TURN_DEAD   到位死区（编码器脉冲，越小越准但越难稳定）
//   ENC_PER_DEG 车转 1° 对应的编码器脉冲差【必须实车标定！】
// ============================================================================
#define TURN_KP     0.5f
#define TURN_MAX    40
#define TURN_MIN    12
#define TURN_DEAD   3
#define ENC_PER_DEG 4

// ============================================================================
// 差速底盘运动接口
//   Diff_Drive —— 差速：设置左右两侧目标速度（板载闭环稳速）
//   Line_Follow —— 循迹：V>0 向前（前灰度）、V<0 向后（后灰度）
//                  位置低通 + PD 纠偏；全黑 → 直行；全白 → 按记忆方向慢速回找
//   Spin       —— 原地旋（开环，调试用）
//   Spin_Angle —— 原地旋（编码器测角闭环，deg 带符号：正=逆时针，待标定）
//   Stop       —— 停车
// ============================================================================
// 返回 0=整帧写进驱动板、1=重试+总线恢复后仍失败（板子会保持上一次速度）
uint8_t Diff_Drive(int16_t V_L, int16_t V_R);
void Line_Follow(int16_t V);
void Spin(int16_t v);
void Spin_Angle(int16_t deg);
void Stop(void);
// 可靠停车：反复下发零速直到驱动板确认收到（返回 1=成功）
uint8_t Stop_Retry(uint8_t tries);

// 循迹封装（无参，底层 Line_Follow 保留）
void Trace_Forward(void);  // 向前循迹（前灰度）
void Trace_Backward(void); // 向后循迹（后灰度）

// 编码器原始读取（32 位，与官方 int32_t EncodeTotal[4] 一致）：
//   enc[0]=203 右后, [1]=202 右前, [2]=204 左后, [3]=201 左前
// 返回 0=读成功、1=读失败（全 0xFF = 总线悬空，enc 已清零，调用方应跳过累加）
// 直接用 int32 做差：16 位不用再靠环绕校正，长距离也不会回绕
uint8_t Encoder_ReadRaw(int32_t enc[4]);

// 编码器调试接口：返回原地旋转角度量（左轮-右轮脉冲差），标定 ENC_PER_DEG 用
int32_t Spin_Encoder(void);

// 走行里程：左右轮脉冲和（直线走≈2×里程，原地旋≈0），圆心全黑测距用
int32_t Encoder_Odometer(void);

// ============================================================================
// 无串口调试变量：Cortex-Debug 在 Watch 窗口添加 **DBG_pos** 等即可实时看值
//   DBG_pos  本次灰度位置（0~70；-1 全白；-2 全黑）
//   DBG_e / DBG_u  误差 / P 差速量
//   DBG_vl / DBG_vr  下发给左/右轮的速度
//   DBG_lost 0=有位置 1=无有效位置
//   DBG_dir  0=向前 1=向后
//   DBG_raw  原始灰度字节（bit7~bit0=探头1~8，1=该探头读到黑）
//   DBG_boot_raw  按 KEY0 那一刻（车静止）的灰度字节
//   DBG_hist[32]  最近 32 次灰度字节滚动记录（跑完暂停后再看）
// ============================================================================
extern volatile int16_t DBG_pos, DBG_e, DBG_u, DBG_vl, DBG_vr;
extern volatile uint8_t DBG_lost, DBG_dir, DBG_raw;
extern volatile uint8_t DBG_boot_raw;
extern volatile uint8_t DBG_hist[32];
extern volatile uint8_t DBG_hist_i;

#endif
